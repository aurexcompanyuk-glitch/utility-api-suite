DEFAULT_KIND = "restaurant"


def curve_for(kind: str, is_weekend: bool) -> tuple:
    """The typical 24-hour shape for a kind of place."""
    entry = KINDS.get(kind) or KINDS[DEFAULT_KIND]
    return entry.weekend if is_weekend else entry.weekday


def label_for(kind: str) -> str:
    entry = KINDS.get(kind)
    return entry.label if entry else kind.replace("_", " ").title()


def group_for(kind: str) -> str:
    entry = KINDS.get(kind)
    return entry.group if entry else "eat"
