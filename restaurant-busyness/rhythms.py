"""Typical daily rhythms per kind of place.

Every venue kind has its own shape: a gym peaks before work and after it,
a nightclub barely exists before 10pm, a bank empties at the weekend.
These curves are the fallback when no measured foot-traffic data is
available for a venue — which is the common case, since no provider
covers every venue on earth.

A curve is 24 values (0-100), index 0 = midnight local time.
`wd` = Monday-Friday, `we` = Saturday/Sunday.

IMPORTANT: a number derived from these is an ESTIMATE, not a
measurement. Anything built on it must say so — see BusynessSource in
busyness.py.
"""

